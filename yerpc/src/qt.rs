impl Method {
    pub fn to_string_qt(&self /* root_namespace: Option<&str> */) -> String {
        let (args, call) = if !self.is_positional {
            if let Some((name, ty)) = self.args.first() {
                (
                    format!("{} {}", TypeInfo::from(*ty).qt_type(), name),
                    name.to_string(),
                )
            } else {
                ("".to_string(), "QJsonValue::Undefined".to_string())
            }
        } else {
            let args = self
                .args
                .iter()
                .map(|(name, arg)| format!("{} {}", TypeInfo::from(*arg).qt_type(), name))
                .collect::<Vec<String>>()
                .join(", ");
            let call = format!(
                "QJsonArray{{{}}}",
                self.args
                    .iter()
                    .map(|(name, _)| format!("toJson({name})"))
                    .collect::<Vec<_>>()
                    .join(", ")
            );
            (args, call)
        };
        let output = self.output.map_or_else(
            || "void".to_string(),
            |output| TypeInfo::from(output).qt_type(),
        );
        let (output, inner_method) = if !self.is_notification {
            (
                format!("[[nodiscard]] std::future<Result<{output}>>"),
                format!("request<{output}>"),
            )
        } else {
            unimplemented!()
            // (output, "notification")
        };
        let docs = if let Some(docs) = &self.docs {
            let docs = docs.split('\n').fold(String::new(), |mut output, s| {
                let _ = writeln!(output, "   *{s}");
                output
            });
            format!("  /**\n{docs}   */")
        } else {
            "".into()
        };
        let qt_name = &self.ts_name;
        let rpc_name = &self.rpc_name;
        format!(
            r#"{docs}
  {output} {qt_name}({args}) {{
    return {inner_method}("{rpc_name}", {call});
  }}

"#,
        )
    }
}
