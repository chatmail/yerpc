use typescript_type_def::TypeDef;

impl TypeInfo {
    fn swift_type(&self) -> String {
        match self {
            TypeInfo::String => "String".to_owned(),
            TypeInfo::Bool => "Bool".to_owned(),
            TypeInfo::Number(n) => match n {
                Number::I8 => "Int8",
                Number::I16 => "Int16",
                Number::I32 => "Int32",
                Number::I64 => "Int64",
                Number::U8 => "UInt8",
                Number::U16 => "UInt16",
                Number::U32 => "UInt32",
                Number::U64 => "UInt64",
                Number::F32 => "Float",
                Number::F64 => "Double",
            }
            .to_owned(),
            TypeInfo::Optional(o) => {
                format!("{}?", o.swift_type())
            }
            TypeInfo::Array(a) => {
                format!("[{}]", a.swift_type())
            }
            TypeInfo::Map(v) => {
                format!("[String: {}]", v.swift_type())
            }
            TypeInfo::Void => "Void".to_owned(),
            TypeInfo::Struct { name, .. }
            | TypeInfo::TaggedEnum { name, .. }
            | TypeInfo::StringEnum { name, .. } => name.clone(),
            TypeInfo::Tuple { name, elements } => name.clone().unwrap_or_else(|| {
                format!(
                    "CodableTuple<{}>",
                    join_with_comma(elements.iter().map(Self::swift_type))
                )
            }),
        }
    }
}

pub fn export_types_to_file<T: TypeDef>(path: &Path) -> io::Result<()> {
    let mut output = format!(
        r#"// AUTO-GENERATED by yerpc-derive

import MetaCodable

struct CodableTuple<each Element: Codable>: Codable {{
    let values: (repeat each Element)

    init(_ values: (repeat each Element)) {{
        self.values = values
    }}

    func encode(to encoder: Encoder) throws {{
        var container = encoder.unkeyedContainer()
        repeat try container.encode(each values)
    }}

    init(from decoder: Decoder) throws {{
        var container = try decoder.unkeyedContainer()
        values = (repeat try container.decode((each Element).self))
    }}
}}

"#
    );
    SwiftGenerator::new().generate(&mut output, &TypeInfo::from(&T::INFO));
    std::fs::write(path, output)
}

#[derive(Default)]
pub struct SwiftGenerator {
    seen: HashSet<String>,
}

impl SwiftGenerator {
    pub fn new() -> Self {
        Self::default()
    }

    fn generate(&mut self, output: &mut String, ty: &TypeInfo) {
        if !self.seen.insert(ty.swift_type()) {
            return;
        };
        match ty {
            TypeInfo::Struct { name, fields } => {
                self.generate_struct(output, name, fields);
            }
            TypeInfo::TaggedEnum { name, variants } => self.generate_enum(output, name, variants),
            TypeInfo::StringEnum { name, variants } => {
                self.generate_enum(
                    output,
                    name,
                    &variants
                        .iter()
                        .map(|name| Variant {
                            name: name.clone(),
                            fields: vec![],
                        })
                        .collect(),
                );
            }
            TypeInfo::Tuple { name, elements } => self.generate_tuple(output, name, elements),
            TypeInfo::Array(ty) | TypeInfo::Optional(ty) | TypeInfo::Map(ty) => {
                self.generate(output, ty)
            }
            TypeInfo::Bool | TypeInfo::Number(_) | TypeInfo::String | TypeInfo::Void => (),
        }
    }

    fn generate_tuple(
        &mut self,
        output: &mut String,
        name: &Option<String>,
        elements: &Vec<TypeInfo>,
    ) {
        for e in elements {
            self.generate(output, e);
        }
        if let Some(name) = name {
            writeln!(
                output,
                "typealias {name} = ({})",
                join_with_comma(elements.iter().map(|ty| ty.swift_type()))
            )
            .unwrap();
        }
    }

    fn generate_enum(&mut self, output: &mut String, uname: &str, variants: &Vec<Variant>) {
        for v in variants {
            for f in &v.fields {
                self.generate(output, &f.ty);
            }
        }
        writeln!(output, "@Codable").unwrap();
        writeln!(output, r#"@CodedAt("kind")"#).unwrap();
        writeln!(output, "enum {uname} {{",).unwrap();
        for Variant { name, fields } in variants {
            let fields = join_with_comma(
                fields
                    .iter()
                    .map(|field| format!("{}: {}", field.name, field.ty.swift_type())),
            );
            if fields.is_empty() {
                writeln!(output, "  case {name}").unwrap()
            } else {
                writeln!(output, "  case {name}({fields})").unwrap()
            };
        }
        writeln!(output, "}}",).unwrap();
    }

    fn generate_struct(&mut self, output: &mut String, sname: &str, fields: &[Field]) {
        for Field { ty, .. } in fields.iter() {
            self.generate(output, ty);
        }
        writeln!(output, "@Codable").unwrap();
        writeln!(output, "struct {sname} {{").unwrap();
        for Field { name, ty } in fields {
            let ty_name = ty.swift_type();
            writeln!(output, "  let {name}: {ty_name}").unwrap();
        }
        writeln!(output, "}};").unwrap();
    }
}

fn join_with_comma(els: impl IntoIterator<Item = String>) -> String {
    els.into_iter()
        .reduce(|a, b| a + ", " + &b)
        .unwrap_or_default()
}

#[test]
fn test_string_enum() {
    #[derive(TypeDef)]
    #[allow(unused)]
    enum Foo {
        Bar,
        Baz,
    }
    let mut out = String::new();
    SwiftGenerator::new().generate(&mut out, &TypeInfo::from(&Foo::INFO));
    insta::assert_snapshot!(out);
}

#[test]
fn test_tuple() {
    #[derive(TypeDef)]
    #[allow(unused)]
    struct Foo(u32, String);
    let mut out = String::new();
    SwiftGenerator::new().generate(&mut out, &TypeInfo::from(&Foo::INFO));
    insta::assert_snapshot!(out);
}

#[test]
fn test_nested_struct() {
    #[derive(TypeDef)]
    #[allow(unused)]
    struct Foo {
        bar: Vec<u8>,
        baz: std::collections::HashMap<String, i8>,
    }
    let mut out = String::new();
    SwiftGenerator::new().generate(&mut out, &TypeInfo::from(&Foo::INFO));
    insta::assert_snapshot!(out);
}

#[test]
fn test_tagged_enum() {
    #[derive(TypeDef)]
    #[serde(tag = "kind")]
    #[allow(unused)]
    enum Foo {
        Bar { name: String, count: u32 },
        Baz,
    }
    let mut out = String::new();
    SwiftGenerator::new().generate(&mut out, &TypeInfo::from(&Foo::INFO));
    insta::assert_snapshot!(out);
}

impl Method {
    pub fn to_string_swift(&self) -> String {
        let (args, call) = if !self.is_positional {
            todo!()
        } else {
            let args = join_with_comma(
                self.args
                    .iter()
                    .map(|(name, arg)| format!("{}: {}", name, TypeInfo::from(*arg).swift_type())),
            );
            let call = format!(
                "[{}]",
                join_with_comma(self.args.iter().map(|(name, _)| name.to_owned()))
            );
            (args, call)
        };
        let output = self.output.map_or_else(
            || "Void".to_string(),
            |output| TypeInfo::from(output).swift_type(),
        );
        let (output, inner_method) = if !self.is_notification {
            (
                format!("Result<{output}, JsonrpcError>"),
                format!("transport.request"),
            )
        } else {
            unimplemented!()
            // (output, "notification")
        };
        let docs = if let Some(docs) = &self.docs {
            let docs = docs.split('\n').fold(String::new(), |mut output, s| {
                let _ = writeln!(output, "   *{s}");
                output
            });
            format!("  /**\n{docs}   */")
        } else {
            "".into()
        };
        let name_camel = &self.rpc_name_camel;
        let rpc_name = &self.rpc_name;
        format!(
            r#"{docs}
  func {name_camel}({args}) async -> {output} {{
    return await {inner_method}(method: "{rpc_name}", params: {call})
  }}

"#,
        )
    }
}
